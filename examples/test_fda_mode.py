"""Test an FDA_MODE transmitter and console against the preset .json they were built from.

Both FDA images carry the one preset, generated by generate_presets.py, at
the end of their application slot: the transmitter its blob (pages 124-125)
and programs the chips from it, the console its HV entry -- the voltage, the
transmitter sensitivity that voltage suits, the settings_crc -- (page 61)
and works out the HV itself: the host selects the preset and gives it the
connected transmitter's sensitivity. Neither image writes those pages, nor
the transmitter's user config. Only input: the preset .json the images were
generated from, or a folder holding just it. HV stays off unless --run
turns it on.

    python examples/test_fda_mode.py --json-preset-directory <preset.json>
    python examples/test_fda_mode.py --json-preset-directory <folder> --duration 1
    python examples/test_fda_mode.py --console-only
    python examples/test_fda_mode.py --json-preset-directory <folder> --run   # start the sequence, for a scope

--run skips the checks below and runs the preset's sequence once, the way a
host would: it loads the preset on both boards (LIFUInterface.load_preset,
with the run length --duration picks and this transmitter's sensitivity),
turns HV on, starts the trigger, and turns HV off when the sequence ends or
on Ctrl+C. The load is on both boards or on neither: if the transmitter or
the console refuses the .json, the error is reported and nothing starts.

Against the transmitter this proves:

  1. The transmitter holds exactly the .json's preset, and only that one.
  2. Each one is the .json's preset, loads on the host's CRC with the run
     length --duration picks, reads back from the chips register for
     register, and sets the trigger to its timing (test_presets.py's
     --verify-preset, on every preset).
  3. The gates hold: an index past the last, a short load, a load with the
     wrong regs_crc, another file's settings_crc or a run length the preset
     lacks, a host register write and a user config write are all refused,
     and after a refused load, or an unload, the trigger will not start.
  4. The delay profiles cycle through the preset's execution order once the
     trigger runs.

Against the console, if one is connected (--console-only checks it alone):

  5. It holds the .json's preset, with its settings_crc, voltage and
     sensitivity (skipped without a .json).
  6. set_voltage and the raw DAC commands are refused, and so is HV on until
     a preset is selected.
  7. A select is refused with the wrong settings_crc, and when the
     transmitter sensitivity it is given puts the voltage outside the
     console's window; inside it, the console applies
     voltage x preset sensitivity / transmitter sensitivity. A refused
     select, or a deselect, leaves nothing selected and HV on refused.
  8. With a transmitter connected that has a sensitivity for the preset's
     frequency in its user config, a select with that value does the same.

The checks leave the transmitter with nothing loaded and the console with
nothing selected.

Each preset's start_C / shutoff_C are part of what (2) compares; the gates
they drive need presets near room temperature, see test_thermal_limits.py.
"""

